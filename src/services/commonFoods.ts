export function searchFoods(query: string, limit = 15): CommonFoodItem[] {
  const normalized = query.trim().toLowerCase();
  if (!normalized) return [];

  // Prefix matches first (more relevant), then other substring matches.
  const startsWith: CommonFoodItem[] = [];
  const contains: CommonFoodItem[] = [];
  for (const food of COMMON_FOODS) {
    const name = food.name.toLowerCase();
    if (name.startsWith(normalized)) {
      startsWith.push(food);
    } else if (name.includes(normalized)) {
      contains.push(food);
    }
  }

  return [...startsWith, ...contains].slice(0, limit);
}

// Scales a per-100g food to a given quantity in grams.
export function scaleFood(food: CommonFoodItem, quantityG: number) {
  const factor = quantityG / 100;
  return {
    calories: Math.round(food.caloriesPer100g * factor),
    proteinG: Math.round(food.proteinPer100g * factor * 10) / 10,
    carbsG: Math.round(food.carbsPer100g * factor * 10) / 10,
    fatG: Math.round(food.fatPer100g * factor * 10) / 10,
  };
}
